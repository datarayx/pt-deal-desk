import type { Metadata } from "next";
import { Suspense } from "react";

import { PageHeader } from "@/components/common/page-header";
import { DataTableSkeleton } from "@/components/data-table/data-table-skeleton";
import { OutboxTable } from "@/features/alerts/components/outbox-table";
import { getOutboxEmails } from "@/features/alerts/queries";

export const metadata: Metadata = { title: "Outbox" };

async function OutboxSection() {
  const emails = await getOutboxEmails();
  return <OutboxTable emails={emails} />;
}

export default function OutboxPage() {
  return (
    <div className="space-y-6">
      <PageHeader
        title="Outbox"
        description="Reminder emails generated by the daily job. In demo mode, nothing is sent."
      />
      <Suspense fallback={<DataTableSkeleton columns={5} rows={6} />}>
        <OutboxSection />
      </Suspense>
    </div>
  );
}
